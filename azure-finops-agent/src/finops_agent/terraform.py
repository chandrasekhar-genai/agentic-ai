"""Turn findings into a reviewable Terraform patch.

* rightsize_vm  -> edit `size` in the matching azurerm_*_virtual_machine block
* nonprod_schedule -> add azurerm_dev_test_global_vm_shutdown_schedule

Blocks are matched on the VM `name` attribute. Nothing is applied; the output
is a unified diff for a pull request, so the normal plan/review/apply pipeline
stays in charge.
"""

from __future__ import annotations

import difflib
import re
from dataclasses import dataclass
from pathlib import Path

from .rules import Finding

_VM_BLOCK = re.compile(r'resource\s+"(azurerm_(?:linux|windows)_virtual_machine)"\s+"([\w-]+)"\s*\{')


@dataclass
class VmBlock:
    file: Path
    rtype: str
    address: str
    start: int
    end: int
    body: str

    @property
    def vm_name(self) -> str | None:
        m = re.search(r'^\s*name\s*=\s*"([^"]+)"', self.body, re.MULTILINE)
        return m.group(1) if m else None


def find_vm_blocks(tf_dir: Path) -> list[VmBlock]:
    blocks = []
    for path in sorted(tf_dir.rglob("*.tf")):
        text = path.read_text(encoding="utf-8")
        for m in _VM_BLOCK.finditer(text):
            depth, i = 0, m.end() - 1
            while i < len(text):
                depth += {"{": 1, "}": -1}.get(text[i], 0)
                if depth == 0:
                    break
                i += 1
            blocks.append(VmBlock(path, m.group(1), f"{m.group(1)}.{m.group(2)}", m.start(), i + 1,
                                  text[m.start(): i + 1]))
    return blocks


def build_patch(findings: list[Finding], tf_dir: str | Path) -> tuple[str, list[str]]:
    """Return (unified diff, notes about findings that could not be mapped)."""
    tf_dir = Path(tf_dir)
    blocks = {b.vm_name: b for b in find_vm_blocks(tf_dir) if b.vm_name}
    edits: dict[Path, str] = {}
    schedules: list[str] = []
    notes: list[str] = []

    for f in findings:
        if f.change.get("type") not in {"resize", "schedule"}:
            continue
        block = blocks.get(f.name)
        if block is None:
            notes.append(f"{f.name}: no azurerm VM block with name = \"{f.name}\" under {tf_dir}")
            continue
        if f.change["type"] == "resize":
            text = edits.get(block.file, block.file.read_text(encoding="utf-8"))
            old = block.body
            new = re.sub(r'(^\s*size\s*=\s*")[^"]+(")', rf'\g<1>{f.change["to"]}\g<2>', old,
                         count=1, flags=re.MULTILINE)
            if new == old:
                notes.append(f"{f.name}: block {block.address} has no literal size attribute")
                continue
            edits[block.file] = text.replace(old, new, 1)
        else:
            local = block.address.split(".", 1)[1]
            schedules.append(
                f'resource "azurerm_dev_test_global_vm_shutdown_schedule" "{local}" {{\n'
                f"  virtual_machine_id    = {block.address}.id\n"
                f"  location              = {block.address}.location\n"
                f"  enabled               = true\n"
                f'  daily_recurrence_time = "{f.change["stop"]}"\n'
                f'  timezone              = "{f.change["timezone"]}"\n\n'
                f"  notification_settings {{\n    enabled = false\n  }}\n\n"
                f'  tags = {{ managed_by = "finops-agent" }}\n}}\n'
            )

    def rel(path: Path) -> str:
        """Path relative to the current directory (run from the repo root so `git apply` works)."""
        try:
            return path.resolve().relative_to(Path.cwd().resolve()).as_posix()
        except ValueError:
            return path.relative_to(tf_dir.parent).as_posix()

    diff: list[str] = []
    for path, new_text in sorted(edits.items()):
        diff += difflib.unified_diff(path.read_text(encoding="utf-8").splitlines(keepends=True),
                                     new_text.splitlines(keepends=True), f"a/{rel(path)}", f"b/{rel(path)}")
    if schedules:
        target = rel(tf_dir / "finops_schedules.tf")
        content = "# Generated by azure-finops-agent: auto-shutdown for non-production VMs\n\n" + "\n".join(schedules)
        diff += difflib.unified_diff([], content.splitlines(keepends=True), "/dev/null", f"b/{target}")
    return "".join(diff), notes
