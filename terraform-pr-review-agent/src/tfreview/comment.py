"""Render the PR comment and create-or-update it on GitHub."""

from __future__ import annotations

import json
import os

import httpx

from .guardrails import Finding
from .plan import Plan
from .scanners import CheckovResult, CostDiff

MARKER = "<!-- tfreview -->"
ICON = {"high": "🔴", "medium": "🟠", "low": "🟡"}


def render(plan: Plan, findings: list[Finding], blocking: list[Finding], checkov: list[CheckovResult],
           cost: CostDiff | None, review: str) -> str:
    c = plan.counts()
    status = "❌ **Blocking findings – changes requested**" if blocking else "✅ **No blocking findings**"
    lines = [
        MARKER,
        "## Terraform review",
        status,
        "",
        f"`+{c['create']}` create · `~{c['update']}` update · `±{c['replace']}` replace · `-{c['delete']}` delete"
        + (f" · cost **{_money(cost)}**/month" if cost else ""),
        "",
        review.strip(),
        "",
    ]
    if findings:
        lines += ["<details open><summary><b>Policy findings</b> "
                  f"({len(findings)})</summary>", "", "| | Rule | Resource | Detail |", "|---|---|---|---|"]
        for f in sorted(findings, key=lambda f: -{"high": 3, "medium": 2, "low": 1}[f.severity]):
            lines.append(f"| {ICON[f.severity]} | `{f.rule}` | `{f.address}` | {f.message} |")
        lines += ["", "</details>", ""]
    if checkov:
        lines += [f"<details><summary><b>Checkov</b> ({len(checkov)} failed checks)</summary>", "",
                  "| Check | Resource | Description |", "|---|---|---|"]
        lines += [f"| `{r.check_id}` | `{r.resource}` | {r.name} |" for r in checkov[:25]]
        lines += ["", "</details>", ""]
    if cost and cost.top:
        lines += ["<details><summary><b>Cost by resource</b> (Infracost)</summary>", "",
                  f"| Resource | Monthly ({cost.currency}) |", "|---|---:|"]
        lines += [f"| `{name}` | {amount:,.2f} |" for name, amount in cost.top]
        lines += ["", "</details>", ""]
    lines.append("<sub>Generated by terraform-pr-review-agent. Policy results are deterministic; "
                 "the narrative is AI-generated and may be wrong.</sub>")
    return "\n".join(lines) + "\n"


def _money(cost: CostDiff) -> str:
    sign = "+" if cost.diff >= 0 else "−"
    return f"{sign}{cost.currency} {abs(cost.diff):,.2f} ({cost.before:,.0f} → {cost.after:,.0f})"


def pr_number() -> int | None:
    path = os.getenv("GITHUB_EVENT_PATH")
    if path and os.path.exists(path):
        with open(path, encoding="utf-8") as f:
            event = json.load(f)
        return (event.get("pull_request") or {}).get("number")
    return None


def upsert(body: str, repo: str, number: int, token: str, api: str | None = None) -> str:
    api = (api or os.getenv("GITHUB_API_URL", "https://api.github.com")).rstrip("/")
    headers = {"Authorization": f"Bearer {token}", "Accept": "application/vnd.github+json",
               "X-GitHub-Api-Version": "2022-11-28"}
    with httpx.Client(base_url=api, headers=headers, timeout=30) as gh:
        existing = None
        page = 1
        while existing is None:
            r = gh.get(f"/repos/{repo}/issues/{number}/comments", params={"per_page": 100, "page": page})
            r.raise_for_status()
            items = r.json()
            existing = next((i for i in items if MARKER in (i.get("body") or "")), None)
            if len(items) < 100:
                break
            page += 1
        if existing:
            gh.patch(f"/repos/{repo}/issues/comments/{existing['id']}", json={"body": body}).raise_for_status()
            return "updated"
        gh.post(f"/repos/{repo}/issues/{number}/comments", json={"body": body}).raise_for_status()
        return "created"
